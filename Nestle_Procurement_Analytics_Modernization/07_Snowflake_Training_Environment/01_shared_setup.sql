-- Grants for TRAINEE_BASE (read only; nobody but admins can write to the shared area).
GRANT USAGE ON WAREHOUSE TRAINING_WH TO ROLE TRAINEE_BASE;
GRANT USAGE ON DATABASE TRAINING_SHARED TO ROLE TRAINEE_BASE;
GRANT USAGE ON SCHEMA TRAINING_SHARED.LANDING TO ROLE TRAINEE_BASE;
GRANT USAGE ON ALL FILE FORMATS IN SCHEMA TRAINING_SHARED.LANDING TO ROLE TRAINEE_BASE;
GRANT USAGE ON FUTURE FILE FORMATS IN SCHEMA TRAINING_SHARED.LANDING TO ROLE TRAINEE_BASE;
GRANT READ ON ALL STAGES IN SCHEMA TRAINING_SHARED.LANDING TO ROLE TRAINEE_BASE;
