-- Shared training infrastructure. Run once as ACCOUNTADMIN in a Snowsight worksheet or snowsql.

USE ROLE ACCOUNTADMIN;

-- Credit guard rail for the trial (~$400 free credit). Adjust CREDIT_QUOTA to your edition/price.
CREATE RESOURCE MONITOR IF NOT EXISTS TRAINING_RM
  WITH CREDIT_QUOTA = 100
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75  PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND
           ON 110 PERCENT DO SUSPEND_IMMEDIATE;

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS TRAINING_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800
  STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 600;

USE ROLE ACCOUNTADMIN;
ALTER WAREHOUSE TRAINING_WH SET RESOURCE_MONITOR = TRAINING_RM;

-- Role every trainee inherits (per-user roles are created by 02_create_users.sql).
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS TRAINEE_BASE COMMENT = 'Common read access to shared landing data + training warehouse';
GRANT ROLE TRAINEE_BASE TO ROLE SYSADMIN;

-- Shared, read-only landing area that trainees load from.
USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS TRAINING_SHARED;
CREATE SCHEMA IF NOT EXISTS TRAINING_SHARED.LANDING;

CREATE FILE FORMAT IF NOT EXISTS TRAINING_SHARED.LANDING.CSV_STANDARD
  TYPE = 'CSV'
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'N/A');

CREATE FILE FORMAT IF NOT EXISTS TRAINING_SHARED.LANDING.JSON_STANDARD
  TYPE = 'JSON'
  STRIP_OUTER_ARRAY = TRUE;

-- Internal stage, loaded from the repo's 04_Data folder by 03_load_shared_data.sql.
CREATE STAGE IF NOT EXISTS TRAINING_SHARED.LANDING.RAW_STAGE
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Nestle procurement source files (csv/ and json/)';

